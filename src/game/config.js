export function setArena(n, melee = false, ffa = false, soccer = false, solo = false){
  const a = soccer ? A4 : (melee ? A3 : (n > 2 ? A2 : A1));
  // 개인전 여부가 바뀌면 팀 판정이 통째로 달라지므로 아레나가 같아도 갱신해야 한다
  // **인원수도 봐야 한다.** 2대2와 3대3은 같은 아레나지만 시작 열 수가 다르다
  // **2대1 여부도** — 팀 나누기가 통째로 달라진다
  if (ARENA.bg === a.bg && ARENA.cols === a.cols && !!ARENA.ffa === !!ffa
      && ARENA.n === n && !!ARENA.solo === !!solo) return ARENA;
  // 그냥 assign하면 **앞 아레나에만 있던 키가 남는다**(melee, straight, wt, wb...).
  // 칼전을 한 판 하고 총격전으로 돌아오면 ARENA.melee가 true로 남아
  // 캐릭터가 칼전 스프라이트로 그려졌다. 매번 비우고 채운다
  for (const key of Object.keys(ARENA)) delete ARENA[key];
  Object.assign(ARENA, a);
  ARENA.ffa = !!ffa;
  ARENA.n = n;
  ARENA.solo = !!solo;      // [stated] 2대1 — 나 혼자(0번) 대 나머지
  GRID_COLS = a.cols; GRID_ROWS = a.rows; GRID_MIDROW = a.mid;
  GRID_X0 = a.x0; GRID_CW = a.cw; GRID_Y0 = a.y0; GRID_CH = a.ch;
  PWf = Math.round(a.pw * FP); PHf = Math.round(a.ph * FP);
  BOFF = Math.round((PWf - BWf) / 2);
  // 얼음 아레나는 벽이 울퉁불퉁해서 **벽 그림 표를 그대로** 써야 한다.
  // 밴드로 칸 단위로 자르면 벽 안쪽 공간에 못 들어가 움직임이 끊긴다.
  // 반대로 던전 아레나(straight)는 벽이 직선이라 밴드에서 표를 만들면 정확히 맞는다
  WALL_L = a.wl; WALL_R = a.wr;
  HOME_COL = a.hc;
  // 5명 이상이면 열이 세 개 필요하다. 두 개뿐이면 개인전에서 자리가 겹친다
  TEAM_COLS = (n >= 5 && a.tc6) ? a.tc6 : a.tc;
  // 중립 행이 있으면 아래 팀은 그 다음 행부터 (가운데 한 칸은 아무도 못 들어간다).
  // 맨 앞뒤 행이 통째로 벽인 경우가 있어 밴드에서 실제 첫·끝 행을 가져온다
  const lo0 = a.mid + (a.neutral ? 1 : 0);
  const firstRow = Math.min(...a.bands.map(b => b[0]));
  const lastRow  = Math.max(...a.bands.map(b => b[1]));
  ROW_MIN = [lo0, firstRow];
  ROW_MAX = [lastRow, a.mid - 1];
  if (a.melee){
    // 칼전은 중앙선도 진영도 없다. 아레나 전체를 양쪽이 같이 쓴다
    const top = Math.round(a.y0 * FP);
    const bot = Math.round((a.y0 + a.ch * a.rows - a.ph) * FP);
    YMIN_S = [top, top]; YMAX_S = [bot, bot];
    ROW_MIN = [0, 0]; ROW_MAX = [a.rows - 1, a.rows - 1];
  } else if (a.neutral){
    const cy = r => a.y0 + a.ch * r;
    // 위아래 끝은 격자가 아니라 바닥 끝까지. 가운데는 중립 행이 경계
    YMIN_S = [ Math.round(cy(lo0) * FP), Math.round((a.yTop ?? cy(firstRow)) * FP) ];
    YMAX_S = [ Math.round(((a.yBot ?? cy(lastRow + 1)) - a.ph) * FP),
               Math.round((cy(a.mid) - a.ph) * FP) ];
  } else {
    // 1대1. **아레나가 화면 전체가 아니므로 H 가 아니라 격자 기준**으로 잡는다.
    // 예전엔 `H/2`·`H - ph` 를 그대로 썼는데, 여백을 준 뒤로는 그러면
    // 아레나 밖(여백)까지 걸어 나간다
    const cy = r => a.y0 + a.ch * r;
    YMIN_S = [ Math.round(cy(a.mid) * FP), Math.round(a.y0 * FP) ];
    YMAX_S = [ Math.round((cy(a.rows) - a.ph) * FP),
               Math.round((cy(a.mid) - a.ph) * FP) ];
  }
  return ARENA;
}
